/* Built-in reference sample set — the 360 labelled points              */
/* (Validation_Samples_CSV.csv, Borj El Arab area). Every supervised     */
/* algorithm trains on these coordinates: real Sentinel-2 features are  */
/* sampled at the points for the requested period, over "AOI ∪ sample   */
/* points" so a small custom AOI never empties the training set.        */
