export interface ReferencePoint {
  classId: number; lon: number; lat: number;
  /** 0.25 = train, 0.75 = validation (grouped per point) */
  split: number;
  /** the professor's dedicated sets: 'train' | 'validation' (built-in points
   *  only — manual points carry the grouped 70/30 split instead) */
  role?: "train" | "validation";
}
/* [classId, lon, lat, role] — role decides the side: 'train' points train the
 * classifier, 'validation' points are withheld. The 20 exact coordinate
 * overlaps between the professor's two files were removed from the VALIDATION
 * side (455 train / 340 strictly disjoint validation), so no point — and no
 * pixel sampled around it — is ever seen on both sides. */
const RAW_POINTS: Array<[number, number, number, string]> = (TRAINING_DATA as any).points;

/** Deterministic, per-class balanced 70/30 split: the points of one class
 *  are ordered by longitude and every 10th index in {2,5,8} is withheld
 *  (≈30 %), so folds interleave along the west–east gradient and every class
 *  keeps a representative share on both sides. Pixels sampled around one
 *  point always stay on the same side — no leakage. */
export function assignSplit<T extends { classId: number; lon: number; lat: number }>(
  pts: T[]
): Array<T & { split: number }> {
  const byClass = new Map<number, T[]>();
  for (const p of pts) {
    const list = byClass.get(p.classId) ?? [];
    list.push(p);
    byClass.set(p.classId, list);
  }
  const out: Array<T & { split: number }> = [];
  for (const list of byClass.values()) {
    list.sort((a, b) => (a.lon - b.lon) || (a.lat - b.lat));
    list.forEach((p, i) => {
      out.push(Object.assign({}, p, { split: i % 10 === 2 || i % 10 === 5 || i % 10 === 8 ? 0.75 : 0.25 }));
    });
  }
  return out;
}

/** the built-in reference points, class ids mapped to the run's scheme.
 *  The professor's dedicated split is authoritative: a 'train' point is a
 *  training pixel, a 'validation' point a withheld test pixel — every pixel
 *  sampled around one point stays on that point's side, so the split is
 *  leakage-free by construction. */
export function referencePoints(scheme: SchemeKey): ReferencePoint[] {
  return RAW_POINTS.map(([classId, lon, lat, role]) => {
    const validation = role === "validation";
    return {
      classId: mapClassId(Number(classId), scheme),
      lon: Number(lon),
      lat: Number(lat),
      role: validation ? "validation" : "train",
      split: validation ? 0.75 : 0.25,
    };
  });
}

/** training region: the AOI united with the sample-point bounding box, so
 *  the monthly composites cover both the AOI and the reference points
 *  (the built-in set lies mostly OUTSIDE the default Borj El Arab AOI). */
function unionRegion(aoi: any, pts: { lon: number; lat: number }[]): any {
  if (!pts.length) return aoi;
  let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity;
  for (const p of pts) {
    if (p.lon < minLon) minLon = p.lon;
    if (p.lon > maxLon) maxLon = p.lon;
    if (p.lat < minLat) minLat = p.lat;
    if (p.lat > maxLat) maxLat = p.lat;
  }
  const box = ee.Geometry.Rectangle(
    [minLon - 0.02, minLat - 0.02, maxLon + 0.02, maxLat + 0.02],
    "EPSG:4326", false
  );
  try {
    return aoi.union(box, 1);
  } catch {
    return box;
  }
}

/** how far the AOI centroid lies from the sample-set centroid (km) — the
 *  "samples_far" note fires beyond 40 km */
export function sampleDistanceKm(aoiGeo: AoiGeoInput | undefined): number {
  const ring: number[][] =
    aoiGeo?.type === "Polygon"
      ? (aoiGeo.coordinates as number[][][])[0]
      : aoiGeo?.type === "MultiPolygon"
        ? (aoiGeo.coordinates as number[][][][])[0][0]
        : (BORJ_COORDS as unknown as number[][]);
  let cx = 0, cy = 0;
  for (const pt of ring) { cx += pt[0]; cy += pt[1]; }
  cx /= ring.length; cy /= ring.length;
  let px = 0, py = 0;
  for (const [, lon, lat] of RAW_POINTS) { px += Number(lon); py += Number(lat); }
  px /= RAW_POINTS.length; py /= RAW_POINTS.length;
  const dLat = (py - cy) * 111.32;
  const dLon = (px - cx) * 111.32 * Math.cos((Math.PI / 180) * ((py + cy) / 2));
  return Math.sqrt(dLat * dLat + dLon * dLon);
}

/** Prepared training set selection is inlined above (selectTrainingPoints). */

/** Manual sample points are usable when at least 20 valid points across ≥ 2
 *  classes were provided — they then REPLACE the built-in set. Fewer or
 *  none → the built-in 360-point reference set is used. */
function manualSampleState(
  points: SampleInput[] | undefined,
  scheme: SchemeKey
) {
  const pts = (points || [])
    .map((s) => ({ classId: mapClassId(s.classId, scheme), lon: s.lon, lat: s.lat }))
    .filter((s) =>
      Number.isFinite(s.lon) && Number.isFinite(s.lat) &&
      SCHEMES[scheme].classes.some((c) => c.id === s.classId));
  const byClass = new Map<number, number>();
  for (const s of pts) byClass.set(s.classId, (byClass.get(s.classId) ?? 0) + 1);
  return { pts, byClass, ok: pts.length >= 20 && byClass.size >= 2 };
}

/** Choose the labelled point set for a supervised run:
 *  1. the user's manual points when at least 20 valid points across ≥ 2
 *     classes were provided — they REPLACE the built-in set;
 *  2. otherwise the built-in reference set — the professor's dedicated
 *     455-point training / 340-point validation split (roles carry the side);
 *  3. out-of-season classes are dropped from BOTH sides (strict seasonal
 *     filtering). */
function selectTrainingPoints(opts: {
  scheme: SchemeKey;
  family: string;
  samplePoints: SampleInput[] | undefined;
}): { points: ReferencePoint[]; kind: "builtin" | "manual" } {
  const active = new Set(activeClassIds(opts.scheme, opts.family));
  const manual = manualSampleState(opts.samplePoints, opts.scheme);
  const base = manual.ok ? assignSplit(manual.pts) : referencePoints(opts.scheme);
  const points = base.filter((p) => active.has(p.classId));
  return { points, kind: manual.ok ? "manual" : "builtin" };
}

/** Feature-collection of buffered training points: every point is buffered by
 *  15 m so ~7 pixels at 10 m are sampled per point — enough rows for the
 *  Mahalanobis covariance while staying inside the homogeneous field patch
 *  around each point. All pixels of one point share the point's split value
 *  (grouped 70/30, no leakage). */
function trainingFC(points: ReferencePoint[]): any {
  return ee.FeatureCollection(
    points.map((p) => ee.Feature(
      ee.Geometry.Point([p.lon, p.lat]).buffer(15),
      { class: p.classId, split: p.split }
    ))
  );
}

/**
 * Sample training pixels around the sample points, dropping points that fall
 * outside the feature stack extent or on fully-masked (cloud) pixels — such
 * points yield null band values that would otherwise crash classifier
 * training with an opaque EE error.
 */
function sampleTraining(feats: any, fc: any) {
  return feats
    .sampleRegions({ collection: fc, properties: ["class", "split"], scale: 10, tileScale: 4 })
    .filter(ee.Filter.notNull(feats.bandNames()));
}

// per-class PA/UA/F1 from a confusion matrix (rows = actual, cols = predicted);
// classIds[i] is the real class id of row/col i (matrix axes are sorted class values)
function perClassMetrics(matrix: number[][], classIds: number[], scheme: SchemeKey = "crops") {
  const n = matrix.length;
  const colSums: number[] = [];
  for (let j = 0; j < n; j++) {
    colSums[j] = 0;
    for (let i = 0; i < n; i++) colSums[j] += matrix[i][j] || 0;
  }
  const out = new Map<number, { pa: number; ua: number; f1: number; support: number }>();
  for (let i = 0; i < n; i++) {
    const cls = classesOf(scheme).find((c) => c.id === classIds[i]);
    if (!cls) continue;
    let rowSum = 0;
    for (let j = 0; j < n; j++) rowSum += matrix[i][j] || 0;
    if (rowSum === 0) continue;
    const correct = matrix[i][i] || 0;
    const pa = rowSum ? correct / rowSum : 0;
    const ua = colSums[i] ? correct / colSums[i] : 0;
    const f1 = pa + ua > 0 ? (2 * pa * ua) / (pa + ua) : 0;
    out.set(cls.id, { pa, ua, f1, support: rowSum });
  }
  return out;
}

