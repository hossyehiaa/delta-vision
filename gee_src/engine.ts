/* Instant scan — reference statistics of the built-in sample set      */
/*                                                                    */
/* No training samples needed: each class is represented by the mean   */
/* and standard deviation of the 9 seasonal summary features MEASURED  */
/* at the labelled points (scheme.json, generated by make_scheme.py).  */
/* Pixels are scored with a Gaussian naive-Bayes distance — an instant */
/* estimate, clearly labelled as such in the UI.                       */
/* ------------------------------------------------------------------ */

/** the 9 seasonal summary features of the instant scan (order = scheme.json) */
export const SIG_FEATURES: string[] = (SCHEME_DATA as any).sig_features;
/** pooled per-feature std across the labelled points (normalisation scales) */
export const SIG_SCALES: number[] = (SCHEME_DATA as any).sig_scales;

/** Instant-scan reference statistics per class per season family: mean/std of
 *  the 9 features measured at the labelled points (make_scheme.py) plus the
 *  class share of the sample set as prior. Nothing hand-calibrated. */
function signatureStats(scheme: SchemeKey, family: string, classId: number): {
  mean: number[]; std: number[]; prior: number; logDet: number;
} | null {
  const s = SCHEMES[scheme];
  const st = (s.signatures[family] ?? {})[String(classId)];
  if (!st) return null;
  const std = (st.std as number[]).map((v) => Math.max(1e-3, v));
  const prior = Math.max(1e-3, Number((s.priors[family] ?? {})[String(classId)] ?? 0));
  const logDet = std.reduce((acc, v) => acc + 2 * Math.log(v), 0);
  return { mean: st.mean as number[], std, prior, logDet };
}

/** Reduced 9-feature seasonal stack the signature classifier works on. */
export function signatureFeatures(s2: any): any {
  const ndvi = s2.select("NDVI");
  const stats = ndvi.reduce(ee.Reducer.percentile([10, 90]))
    .addBands(ndvi.reduce(ee.Reducer.mean()).rename("NDVI_mean"));
  return ee.Image.cat([
    stats,
    s2.select("NDWI").mean().rename("NDWI_mean"),
    s2.select("NDMI").mean().rename("NDMI_mean"),
    s2.select(["B4", "B8", "B11", "B12"]).median()
      .rename(["B4_median", "B8_median", "B11_median", "B12_median"]),
  ]);
}

/** Instant scan (no training samples): Gaussian naive-Bayes distance to the
 *  measured per-class reference statistics of the built-in sample set:
 *  d_c(x) = Σ_f (x_f − μ_cf)²/σ_cf² + Σ_f ln σ_cf² − 2 ln prior_c.
 *  Only the season's active classes compete; the result is an instant
 *  estimate, clearly labelled as such in the UI. */
export function signatureClassifyImage(
  sigFeats: any,
  scheme: SchemeKey,
  family: string
): any {
  const x = sigFeats.select(SIG_FEATURES);
  const active = activeClassIds(scheme, family);
  const dists: any[] = [];
  const owner: number[] = [];
  for (const classId of active) {
    const st = signatureStats(scheme, family, classId);
    if (!st) continue;
    const d = x
      .subtract(ee.Image.constant(st.mean))
      .divide(ee.Image.constant(st.std))
      .pow(2)
      .reduce(ee.Reducer.sum())
      .add(st.logDet)
      .subtract(2 * Math.log(st.prior))
      .rename(`d${classId}`);
    dists.push(d);
    owner.push(classId);
  }
  if (!dists.length) throw new GEEError("no_active_classes");
  // argmin over the class-distance bands (first index wins ties — deterministic)
  let arg = ee.Image(0).rename("argmin");
  let best = dists[0];
  for (let k = 1; k < dists.length; k++) {
    const cur = dists[k];
    arg = arg.where(cur.lt(best), ee.Image.constant(k));
    best = best.min(cur);
  }
  let out = ee.Image.constant(owner[0]).rename("classification");
  for (let k = 1; k < owner.length; k++) {
    out = out.where(arg.eq(k), ee.Image.constant(owner[k]));
  }
  return out;
}

