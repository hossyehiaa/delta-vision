/** Earth Engine occasionally rejects back-to-back heavy graphs with a
 *  transient "capacity exceeded" error — retry such runs once after a pause
 *  instead of failing the user's request. */
async function withCapacityRetry<T>(fn: () => Promise<T>, attempts = 2): Promise<T> {
  try {
    return await fn();
  } catch (e) {
    const msg = String((e as Error)?.message ?? e);
    if (attempts > 1 && /capacity exceeded|overloaded|too many concurrent|timeout/i.test(msg)) {
      await new Promise((r) => setTimeout(r, 12000));
      return withCapacityRetry(fn, attempts - 1);
    }
    throw e;
  }
}

async function runClassificationOnce(input: RunInput): Promise<RunResult> {
  const t0 = Date.now();
  await getEE();
  const scheme = schemeOf(input.scheme);
  const aoi = makeAoi(input.aoiGeo);
  const { start, end, family: resolvedFamily } = resolvePeriod(input);
  // strict seasonal filtering: the crop scheme never mixes winter and summer
  const family = runFamily(scheme, resolvedFamily, start, end);
  const active = activeClassIds(scheme, family);
  const excluded = scheme === "crops"
    ? SCHEMES.crops.classes.map((c) => c.id).filter((id) => !active.includes(id))
    : [];
  const cloud = input.cloudMax ?? 60;
  const rfTrees = input.rfTrees ?? 100;
  const knnK = input.knnK ?? 5;
  const kClusters = Math.min(Math.max(input.kClusters ?? 8, 2), 30);

  // labelled points behind this run (already filtered to in-season classes)
  const { points: trainingPoints, kind: sampleSource } = selectTrainingPoints({
    scheme, family, samplePoints: input.samplePoints,
  });
  const pointCounts: Record<string, number> = {};
  for (const p of trainingPoints) {
    pointCounts[String(p.classId)] = (pointCounts[String(p.classId)] ?? 0) + 1;
  }

  // feature stack over "AOI ∪ sample points": the built-in reference points
  // lie mostly OUTSIDE the default Borj El Arab AOI, so features must be
  // built over the union or the training set would come back empty
  const region = unionRegion(aoi, trainingPoints);
  // independent count — kicked off immediately, awaited with the other
  // round trips at the end (it never gates the graph construction); the
  // immediate catch keeps an early friendly error from leaving an unhandled
  // rejection behind
  const nImagesP = p<number>((cb) =>
    rawCollection(aoi, start, end, cloud).size().getInfo(cb)).catch(() => 0);
  const s2 = getS2(region, start, end, cloud);
  const feats = buildFeatures(s2, start, end);

  let classified: any;
  let oa: number | null = null;
  let kappa: number | null = null;
  let perClass: Map<number, { pa: number; ua: number; f1: number; support: number }> | null = null;
  let confusion: { classIds: number[]; rows: number[][]; total?: number; nValPoints?: number } | null = null;
  let nTrain = 0, nVal = 0;
  let nValPoints = 0;
  let nTrainPoints = 0;
  let accP: Promise<any> | null = null;
  let training: any = null;   // the run's training table (supervised branch)
  let noteCode: string | undefined;
  const notes: string[] = [];
  const addNote = (code: string) => { if (!notes.includes(code)) notes.push(code); };
  if (scheme === "crops" && resolvedFamily === "full") addNote("season_detected");
  if (sampleDistanceKm(input.aoiGeo) > 40) addNote("samples_far");
  let vis: { min: string; max: string; palette: string };
  const paletteCsv = scheme === "crops" ? PALETTE_CSV : GENERAL_PALETTE_CSV;
  const visMax = String(classesOf(scheme).length);

  if (input.algorithm === "signature") {
    // ---- instant scan: measured reference statistics, no training ----
    const sig = signatureFeatures(s2);
    classified = signatureClassifyImage(sig, scheme, family).clip(aoi);
    vis = { min: "1", max: visMax, palette: paletteCsv };
    noteCode = "instant_estimate";
    addNote("instant_estimate");
    nTrain = 0;
    nVal = 0;
  } else if (input.algorithm === "kmeans") {
    const ktrain = feats.sample({ region: aoi, scale: 100, numPixels: 2500, seed: 1 });
    const clusterer = ee.Clusterer.wekaKMeans(kClusters).train(ktrain);
    classified = feats.cluster(clusterer).clip(aoi);
    vis = {
      min: "0", max: String(kClusters - 1),
      palette: KMEANS_PALETTE.slice(0, kClusters).join(","),
    };
    noteCode = "kmeans_no_accuracy";
    addNote("kmeans_no_accuracy");
  } else {
    // training table: sampleRegions over the buffered labelled points
    // (the compact server-side graph — identical request → EE's own
    // computation cache makes repeat runs fast)
    nValPoints = trainingPoints.filter((pt) => (pt.split ?? 0) >= 0.7).length;
    nTrainPoints = trainingPoints.length - nValPoints;
    training = sampleTraining(feats, trainingFC(trainingPoints));
    const train = training.filter(ee.Filter.lt("split", 0.7));
    const val = training.filter(ee.Filter.gte("split", 0.7));

    // fail fast with a friendly error when no sample point yielded a pixel
    [nTrain, nVal] = await Promise.all([
      p<number>((cb) => train.size().getInfo(cb)),
      p<number>((cb) => val.size().getInfo(cb)),
    ]);
    if (nTrain === 0) throw new GEEError("samples_outside_aoi");

    // Mahalanobis inverts a covariance matrix over the feature bands: the
    // full monthly stack (21–45 highly collinear bands) is rank-deficient for
    // 360 reference points, so it runs on the 9 decorrelated seasonal summary
    // bands — pre-checked so it fails friendly, never opaquely server-side.
    const inputProperties = input.algorithm === "mindist_m"
      ? ee.List(MINDIST_BANDS)
      : feats.bandNames();
    const classifier = input.algorithm === "mlp"
      ? null // hybrid: trained in Node below, applied via mlpClassifyImage
      : makeClassifier(input.algorithm, rfTrees, knnK).train({
          features: train, classProperty: "class", inputProperties,
        });
    classified = input.algorithm === "mlp"
      ? null // assigned after training
      : feats.classify(classifier!).clip(aoi);
    vis = { min: "1", max: visMax, palette: paletteCsv };

    if (input.algorithm === "mindist_m") {
      const hist = await p<Record<string, number>>((cb) =>
        train.aggregate_histogram("class").getInfo(cb));
      const counts = Object.values(hist || {});
      const minCount = counts.length ? Math.min(...counts) : 0;
      if (minCount <= MINDIST_BANDS.length) {
        throw new GEEError("mahalanobis_needs_samples",
          `Mahalanobis needs more than ${MINDIST_BANDS.length} training pixels per class (smallest class: ${minCount})`);
      }
    }

    if (input.algorithm === "mlp") {
      // ---- hybrid MLP: train on this Node process, replay on EE per pixel ----
      const bandNames: string[] = await p<any>((cb) => feats.bandNames().getInfo(cb));
      const [trainRows, valRows] = await Promise.all([
        fcToMlpRows(train, bandNames),
        fcToMlpRows(val, bandNames),
      ]);
      const model = mlpTrain(trainRows, bandNames, {
        hidden: input.mlpHidden, epochs: input.mlpEpochs,
      });
      classified = mlpClassifyImage(feats, model).clip(aoi);
      if (nVal >= 10 && valRows.length > 0) {
        const cm = mlpConfusion(model, valRows);
        oa = cm.oa;
        kappa = cm.kappa;
        perClass = perClassMetrics(cm.rows, cm.classIds, scheme);
        const total = cm.rows.reduce((s, row) => s + row.reduce((s2, v) => s2 + v, 0), 0);
        confusion = { classIds: cm.classIds, rows: cm.rows, total, nValPoints: nValPoints || nVal };
      } else {
        noteCode = "no_accuracy";
        addNote("no_accuracy");
      }
    } else if (nVal >= 10) {
      const cm = val.classify(classifier!).errorMatrix("class", "classification");
      // the accuracy evaluation only depends on the trained classifier, so it
      // runs concurrently with the tiles / areas / download round trips below
      accP = p<any>((cb) => ee.Dictionary({
        oa: cm.accuracy(), kappa: cm.kappa(), matrix: cm.array().toList(),
        classes: val.aggregate_array("class").distinct().sort(),
      }).getInfo(cb)).catch((err: unknown) => {
        const msg = String((err as Error)?.message ?? err);
        if (/covariance|singular/i.test(msg)) {
          throw new GEEError("mahalanobis_needs_samples", msg);
        }
        throw err;
      });
    } else {
      noteCode = "no_accuracy";
      addNote("no_accuracy");
    }
  }

  // thumb-only mode (renderThumbUrl): stop once the classified image exists —
  // the publication PNG is rendered on demand, never during a normal run
  if ((input as any).thumbOnly) {
    if (accP) accP.catch(() => { /* not needed for the export */ });
    const thumbUrl = await p<string>((cb) => (classified as any).visualize(vis).getThumbURL({
      region: aoi.bounds(), dimensions: (input as any).thumbDim || 1400, format: "png",
    }, cb)).catch(() => null);
    return {
      mode: "live", algorithm: input.algorithm, season: input.season, scheme,
      family, activeClassIds: active, excludedClassIds: excluded,
      dateFrom: start, dateTo: end,
      tileUrl: null, oa: null, kappa: null, classes: [],
      confusion: null, nImages: 0, nTrain: 0, nVal: 0,
      durationMs: Date.now() - t0, downloadUrl: null, thumbUrl,
      notes: notes.length ? notes : undefined,
      areaKm2: 0, sampleSource, nReferencePoints: trainingPoints.length,
    } as RunResult;
  }

  // All independent server round trips at once: tiles, class areas, the
  // GeoTIFF link and the accuracy evaluation (plus the image count started
  // earlier) — sequential awaits here were pure latency.
  // Area aggregation ladder: 20 m keeps the class shares close to the 10 m
  // classification (AOIs ≤ 200 km²). Above that the measured cost of a 20–30 m
  // reduceRegion over e.g. Borj El Arab (597 km²) is ~24 s on a cold EE cache
  // (vs ~8–10 s at 100 m), so large AOIs use 60 m — finer than the previous
  // 100 m, fast enough, and the shares are rescaled to the exact geodesic
  // total anyway. tileScale 4 + bestEffort prevent memory spikes.
  const aoiM2 = aoiGeoAreaM2(input.aoiGeo);
  const areaScaleM = aoiM2 > 200e6 ? 60 : 20;
  const timings: [string, number][] = [];
  const trace = (label: string, pr: Promise<any>): Promise<any> => {
    if (!process.env.DV_TRACE) return pr;
    const t1 = Date.now();
    return pr.then((v) => { timings.push([label, Date.now() - t1]); return v; },
      (e) => { timings.push([label, Date.now() - t1]); throw e; });
  };
  const mapIdP = p<any>((cb) => ee.data.getMapId({ image: classified, ...vis }, cb));
  const areasP = p<any>((cb) => ee.Image.pixelArea().addBands(classified).reduceRegion({
    reducer: ee.Reducer.sum().group({ groupField: 1, groupName: "class" }),
    geometry: aoi, scale: areaScaleM, tileScale: 4, bestEffort: true, maxPixels: 1e13,
  }).getInfo(cb));
  // GeoTIFF: single-band uint8 clipped classification. 10 m exceeds the
  // synchronous download memory budget on large AOIs ("User memory limit
  // exceeded"), so the scale steps up automatically — 10 m ≤ 100 km²,
  // 20 m ≤ 300 km², 30 m above (Borj El Arab).
  const tifScale = aoiM2 <= 100e6 ? 10 : aoiM2 <= 300e6 ? 20 : 30;
  const tifName = `deltavision_${scheme}_${input.algorithm}_${start}_${end}.tif`.replace(/-/g, "");
  const downloadP = (scale: number) =>
    p<string>((cb) => classified.toByte().getDownloadURL({
      name: tifName, scale, region: aoi, crs: EXPORT_CRS, format: "GeoTIFF",
    }, cb)).catch(() => null);
  let mapId: any;
  let areaRes: any;
  let downloadUrl: string | null = null;
  let downloadScaleM: number | undefined;
  let nImages = 0;
  try {
    const settled = await Promise.all([
      trace("mapId", mapIdP),
      trace("areas", areasP),
      trace("download", downloadP(tifScale)),
      trace("nImages", nImagesP),
      trace("acc", accP ?? Promise.resolve(null)),
    ]) as [any, any, string | null, number, any];
    mapId = settled[0];
    areaRes = settled[1];
    if (settled[2]) {
      downloadUrl = settled[2]; downloadScaleM = tifScale;
    } else {
      // first scale failed (memory) → step straight to the coarsest safe one
      const dl2 = await downloadP(30);
      if (dl2) { downloadUrl = dl2; downloadScaleM = 30; }
    }
    nImages = settled[3];
    const acc = settled[4];
    if (acc) {
      oa = Number(acc.oa); kappa = Number(acc.kappa);
      const valClasses: number[] = (acc.classes || []).map((x: unknown) => Number(x));
      const raw: number[][] = (acc.matrix || []).map((row: unknown[]) =>
        (row as unknown[]).map((x) => Number(x)));
      // EE error matrices are indexed by class VALUE (0..maxValue), so they
      // arrive with empty rows/cols for unsampled ids. Compact them to the
      // axes actually present: validation classes + predicted classes.
      const colTotal = (idx: number) => raw.reduce((s, row) => s + (row[idx] || 0), 0);
      const predClasses = raw.map((_, idx) => idx).filter((idx) => colTotal(idx) > 0);
      const axes = Array.from(new Set([...valClasses, ...predClasses]))
        .filter((v) => v > 0)
        .sort((a, b) => a - b);
      if (axes.length > 1 && Math.max(...axes) < raw.length) {
        const compact = axes.map((a) => axes.map((p2) => raw[a]?.[p2] || 0));
        perClass = perClassMetrics(compact, axes, scheme);
        const total = compact.reduce((s, row) => s + row.reduce((s2, v) => s2 + v, 0), 0);
        confusion = { classIds: axes, rows: compact, total, nValPoints: nValPoints || nVal };
      }
    }
  } catch (e) {
    // map known server errors to friendly codes (e.g. singular covariance)
    const msg = String((e as Error)?.message ?? e);
    if (/covariance|singular/i.test(msg)) {
      throw new GEEError("mahalanobis_needs_samples", msg);
    }
    throw e;
  }
  if (process.env.DV_TRACE && timings.length) {
    console.error("DV_TRACE " + JSON.stringify(Object.fromEntries(timings)));
  }
  if (!nImages) throw new GEEError("no_images");

  const groups: { class: number; sum: number }[] = areaRes.groups || [];
  const totalM2 = groups.reduce((s, g) => s + g.sum, 0);
  // Single source of truth for the TOTAL area: the exact geodesic polygon
  // area (same formula as the client's geo.ts / PostGIS ST_Area). Class pixel
  // areas are measured at the areaScaleM ladder, so they are rescaled
  // proportionally to sum exactly to it — every panel then shows identical
  // strings.
  const areaScale = totalM2 > 0 ? aoiM2 / totalM2 : 1;

  // rounding fixup: displayed percentages must sum to exactly 100.0
  const percentOf = (m2: number) => (totalM2 ? +((m2 / totalM2) * 100).toFixed(1) : 0);
  const percentSum = groups.reduce((s, g) => s + percentOf(g.sum), 0);
  const percentDrift = +(100 - percentSum).toFixed(1);
  const biggest = groups.reduce((a, b) => (b.sum > (a?.sum ?? -1) ? b : a), groups[0]);
  const fixedPercent = new Map<number, number>();
  if (biggest && percentDrift !== 0) fixedPercent.set(
    biggest.class, +(percentOf(biggest.sum) + percentDrift).toFixed(1)
  );

  // merge area + accuracy into class rows
  const rowsMap = new Map<number, ClassRow>();
  for (const g of groups) {
    // kmeans groups are 0-based; supervised are class ids
    const id = input.algorithm === "kmeans" ? g.class + 1 : g.class;
    const base = input.algorithm === "kmeans"
      ? { id, code: `C${g.class + 1}`, en: `Cluster ${g.class + 1}`, ar: `عنقود ${g.class + 1}`, color: `#${KMEANS_PALETTE[g.class % KMEANS_PALETTE.length]}` }
      : classesOf(scheme).find((c) => c.id === id) || classesOf(scheme)[0];
    rowsMap.set(id, {
      classId: id, code: base.code, en: base.en, ar: base.ar, color: base.color,
      areaKm2: +((g.sum * areaScale) / 1e6).toFixed(2),
      percent: fixedPercent.get(g.class) ?? percentOf(g.sum),
      pa: null, ua: null, f1: null, support: 0,
    });
  }
  if (perClass) {
    for (const [id, m] of perClass) {
      const cls = classesOf(scheme).find((c) => c.id === id);
      if (!cls) continue;
      const existing = rowsMap.get(id);
      const row: ClassRow = existing ?? {
        classId: id, code: cls.code, en: cls.en, ar: cls.ar, color: cls.color,
        areaKm2: 0, percent: 0, pa: null, ua: null, f1: null, support: 0,
      };
      row.pa = +m.pa.toFixed(3); row.ua = +m.ua.toFixed(3); row.f1 = +m.f1.toFixed(3);
      row.support = m.support;
      rowsMap.set(id, row);
    }
  }
  const classes = [...rowsMap.values()].sort((a, b) => b.areaKm2 - a.areaKm2);

  return {
    mode: "live",
    algorithm: input.algorithm,
    season: input.season,
    scheme,
    family,
    activeClassIds: active,
    excludedClassIds: excluded,
    dateFrom: start,
    dateTo: end,
    tileUrl: tileTemplate(mapId),
    oa, kappa, classes,
    confusion,
    nImages, nTrain, nVal,
    durationMs: Date.now() - t0,
    downloadUrl,
    downloadScaleM: downloadScaleM ?? (downloadUrl ? tifScale : undefined),
    thumbUrl: null,
    nValPoints: nValPoints || nVal,
    nTrainPoints: nTrainPoints || nTrain,
    noteCode,
    notes: notes.length ? notes : undefined,
    areaKm2: +(aoiM2 / 1e6).toFixed(2),
    aoiName: input.aoiName ?? null,
    sampleSource,
    sampleClassCounts: pointCounts,
    nReferencePoints: trainingPoints.length,
  };
}

export async function runClassification(input: RunInput): Promise<RunResult> {
  return withCapacityRetry(() => runClassificationOnce(input));
}

/** Publication PNG of the classified AOI, rendered on demand by a single
 *  synchronous Earth Engine request (no tile storm, no client rate limits).
 *  The caller fetches the returned URL server-side and streams the bytes.
 *  ~1400 px keeps the render inside EE's synchronous memory budget; the
 *  client upscales to >= 2000 px with nearest-neighbour. */
export async function renderThumbUrl(input: RunInput & { thumbDim?: number }): Promise<{ thumbUrl: string }> {
  const res = await withCapacityRetry(() =>
    runClassificationOnce({ ...input, thumbOnly: true, thumbDim: input.thumbDim } as RunInput));
  if (!res.thumbUrl) throw new GEEError("thumb_failed", "the classified PNG could not be rendered");
  return { thumbUrl: res.thumbUrl };
}



/** Compare all supervised algorithms; returns summary + full result of the best. */
async function compareAllOnce(input: PeriodInput & {
  cloudMax?: number; rfTrees?: number; knnK?: number;
  mlpHidden?: number; mlpEpochs?: number;
  samplePoints?: SampleInput[];
  aoiGeo?: AoiGeoInput;
  aoiName?: string;
  scheme?: SchemeKey;
}): Promise<{
  summary: CompareSummaryRow[];
  best: RunResult;
}> {
  await getEE();
  const scheme = schemeOf(input.scheme);
  const aoi = makeAoi(input.aoiGeo);
  const { start, end, family: resolvedFamily } = resolvePeriod(input);
  const family = runFamily(scheme, resolvedFamily, start, end);
  const cloud = input.cloudMax ?? 60;
  const rfTrees = input.rfTrees ?? 100;
  const knnK = input.knnK ?? 5;

  // training set: manual points when sufficient, otherwise the built-in
  // 360-point reference set — sampled over "AOI ∪ points"
  const { points: trainingPoints } = selectTrainingPoints({
    scheme, family, samplePoints: input.samplePoints,
  });
  if (trainingPoints.length < 20) throw new GEEError("too_few_samples");
  const region = unionRegion(aoi, trainingPoints);
  const nImages = await p<number>((cb) =>
    rawCollection(aoi, start, end, cloud).size().getInfo(cb));
  if (process.env.DV_TRACE && timings.length) {
    console.error("DV_TRACE " + JSON.stringify(Object.fromEntries(timings)));
  }
  if (!nImages) throw new GEEError("no_images");
  const s2 = getS2(region, start, end, cloud);
  const feats = buildFeatures(s2, start, end);
  const training = sampleTraining(feats, trainingFC(trainingPoints));
  const nSampled = await p<number>((cb) => training.size().getInfo(cb));
  if (!nSampled) throw new GEEError("samples_outside_aoi");
  const train = training.filter(ee.Filter.lt("split", 0.7));
  const val = training.filter(ee.Filter.gte("split", 0.7));

  // MLP trains on this Node process — fetch its feature tables once up front
  // and reuse them for training + validation (same split as the GEE path).
  let mlpData: { bandNames: string[]; trainRows: MlpRow[]; valRows: MlpRow[] } | null = null;
  if (SUPERVISED_KEYS.includes("mlp")) {
    const bandNames: string[] = await p<any>((cb) => feats.bandNames().getInfo(cb));
    const [trainRows, valRows] = await Promise.all([
      fcToMlpRows(train, bandNames),
      fcToMlpRows(val, bandNames),
    ]);
    mlpData = { bandNames, trainRows, valRows };
  }

  const summary: CompareSummaryRow[] = [];
  for (const key of SUPERVISED_KEYS) {
    try {
      let oa: number | null;
      let kappa: number | null;
      if (key === "mlp") {
        if (!mlpData || mlpData.valRows.length === 0) {
          throw new GEEError("mlp_needs_classes", "no validation rows for MLP");
        }
        const model = mlpTrain(mlpData.trainRows, mlpData.bandNames, {
          hidden: input.mlpHidden, epochs: input.mlpEpochs,
        });
        const cm = mlpConfusion(model, mlpData.valRows);
        oa = cm.oa; kappa = cm.kappa;
      } else {
        const classifier = makeClassifier(key, rfTrees, knnK).train({
          features: train, classProperty: "class",
          inputProperties: key === "mindist_m" ? ee.List(MINDIST_BANDS) : feats.bandNames(),
        });
        const cm = val.classify(classifier).errorMatrix("class", "classification");
        const acc = await p<any>((cb) => ee.Dictionary({
          oa: cm.accuracy(), kappa: cm.kappa(),
        }).getInfo(cb));
        oa = Number(acc.oa); kappa = Number(acc.kappa);
      }
      summary.push({ algorithm: key, oa, kappa, nVal: 0 });
    } catch (err) {
      // one algorithm failing (e.g. Mahalanobis with few samples per class)
      // must not kill the whole comparison — mark it as failed and continue.
      console.error(`compareAll: algorithm ${key} failed:`,
        String((err as Error)?.message ?? err).slice(0, 200));
      summary.push({ algorithm: key, oa: null, kappa: null, nVal: 0 });
    }
  }
  if (!summary.some((s) => s.oa != null)) {
    throw new GEEError("all_algorithms_failed", "every supervised algorithm failed to train");
  }
  summary.sort((a, b) => (b.oa ?? -1) - (a.oa ?? -1));
  const best = await runClassification({
    ...input, scheme, algorithm: summary[0].algorithm, kind: "run",
    knnK, mlpHidden: input.mlpHidden, mlpEpochs: input.mlpEpochs,
  });
  for (const row of summary) row.nVal = best.nVal;
  return { summary, best };
}

export async function compareAll(input: Parameters<typeof compareAllOnce>[0]): Promise<{
  summary: CompareSummaryRow[];
  best: RunResult;
}> {
  return withCapacityRetry(() => compareAllOnce(input));
}
