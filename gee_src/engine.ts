export function resolvePeriod(input: PeriodInput): {
  start: string; end: string; season: SeasonKey; family: SeasonFamily;
} {
  const y = input.year ?? 2026;
  let start = "", end = "", season: SeasonKey = input.season;
  if (input.season === "winter") { start = `${y - 1}-11-01`; end = `${y}-04-30`; }
  else if (input.season === "early_winter") { start = `${y - 1}-10-01`; end = `${y}-01-31`; }
  else if (input.season === "late_winter") { start = `${y}-02-01`; end = `${y}-05-31`; }
  else if (input.season === "summer") { start = `${y}-05-01`; end = `${y}-10-31`; }
  else if (input.season === "summer_peak") { start = `${y}-06-01`; end = `${y}-09-30`; }
  else if (input.season === "full") { start = `${y}-01-01`; end = `${y}-12-31`; }
  else {
    season = "custom";
    if (!input.dateFrom || !input.dateTo || input.dateFrom >= input.dateTo) {
      throw new GEEError("bad_date_range");
    }
    start = input.dateFrom; end = input.dateTo;
  }
  return { start, end, season, family: seasonFamilyOf(season, start, end) };
}

const PRESET_FAMILY: Record<string, SeasonFamily> = {
  winter: "winter", early_winter: "winter", late_winter: "winter",
  summer: "summer", summer_peak: "summer", full: "full",
};

/** Season family of a period: winter = Nov–Apr months, summer = May–Oct.
 *  For a custom range the DOMINANT family wins (tie → the family of the
 *  first month), so winter and summer crops never mix in one model —
 *  even when a custom range straddles both seasons. */
export function detectSeasonFamily(startISO: string, endISO: string): Exclude<SeasonFamily, "full"> {
  const a = new Date(`${startISO}T00:00:00Z`).getTime();
  const b = new Date(`${endISO}T00:00:00Z`).getTime();
  const firstMonth = new Date(`${startISO}T00:00:00Z`).getUTCMonth() + 1;
  if (!Number.isFinite(a) || !Number.isFinite(b) || b < a) return "winter";
  const isWinter = (m: number) => m === 11 || m === 12 || m <= 4;
  let winter = 0, summer = 0, n = 0;
  const d = new Date(a);
  for (; d.getTime() <= b && n < 48; n++, d.setUTCMonth(d.getUTCMonth() + 1)) {
    if (isWinter(d.getUTCMonth() + 1)) winter++; else summer++;
  }
  if (winter > summer) return "winter";
  if (summer > winter) return "summer";
  return isWinter(firstMonth) ? "winter" : "summer";
}

/** Season family for a resolved period ("custom" detects from the dates). */
export function seasonFamilyOf(season: SeasonKey, start?: string, end?: string): SeasonFamily {
  if (season === "custom") return detectSeasonFamily(start ?? "", end ?? "");
  return PRESET_FAMILY[season] ?? "winter";
}

/** The family a RUN uses: for the crop scheme a "full" family is collapsed
 *  to the dominant seasonal family (strict seasonal filtering); the land-cover
 *  scheme keeps "full" (all 4 classes are always in season). */
export function runFamily(scheme: SchemeKey, family: SeasonFamily, start: string, end: string): Exclude<SeasonFamily, "full"> | "full" {
  if (scheme === "crops" && family === "full") return detectSeasonFamily(start, end);
  return family;
}

