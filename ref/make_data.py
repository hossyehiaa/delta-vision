# -*- coding: utf-8 -*-
"""
make_data.py — generate src/data.js for Delta Vision from two inputs:
  1. the engine's spectral data JSON (signatures, priors, active classes, feature scales)
  2. the user's Borj El Arab shapefile → a simplified boundary used as the built-in sample area

Usage: python3 -I make_data.py <spectral_json> <bourj.shp> <out_data.js> <out_bourj_geojson>
The numbers are copied, never typed by hand, so data.js always matches the engine file.
"""
import json, sys

import geopandas as gpd
from pyproj import CRS, Geod, Transformer

spectral_path, shp_path, out_js, out_geojson = sys.argv[1:5]

data = json.load(open(spectral_path, encoding="utf-8"))
geod = Geod(ellps="WGS84")


def geod_area(g):
    return abs(geod.geometry_area_perimeter(g)[0])


gdf = gpd.read_file(shp_path)
src_crs = CRS.from_user_input(gdf.crs)
utm = CRS.from_epsg(32635)
to_utm = Transformer.from_crs(src_crs, utm, always_xy=True)
to_wgs = Transformer.from_crs(utm, CRS.from_epsg(4326), always_xy=True)

# largest polygon only, simplified on the UTM plane (metres) so the tolerance means real metres
geom = max(gdf.geometry, key=lambda g: g.area)
g_utm = gpd.GeoSeries([geom], crs=src_crs).to_crs(utm).iloc[0]
full = gpd.GeoSeries([geom], crs=src_crs).to_crs(4326).iloc[0]
ring = None
for tol in (40, 60, 80, 100, 120, 150):
    s = g_utm.simplify(tol, preserve_topology=True)
    g_ll = gpd.GeoSeries([s], crs=utm).to_crs(4326).iloc[0]
    ring = [[round(x, 5), round(y, 5)] for x, y in g_ll.exterior.coords]
    if len(ring) <= 220:
        break
simp_area = geod_area(g_ll)
full_area = geod_area(full)
assert ring[0] == ring[-1], "ring must be closed"
print("source crs      :", src_crs.to_string()[:90])
print("vertices        :", len(full.exterior.coords), "->", len(ring), "(tolerance %d m)" % tol)
print("geodesic area m2: %.3f -> %.3f  (%.3f %% off)" % (full_area, simp_area, 100 * (simp_area - full_area) / full_area))
print("feddan          : %.3f -> %.3f" % (full_area / 4200, simp_area / 4200))

bourj = {
    "name": "Borj El Arab",
    "nameAr": "برج العرب",
    "areaM2": simp_area,
    "sourceAreaM2": full_area,
    "vertices": len(ring),
    "ring": ring,
}
json.dump({"type": "FeatureCollection", "features": [{"type": "Feature", "properties": {"name": "Borj El Arab"}, "geometry": {"type": "Polygon", "coordinates": [ring]}}]},
          open(out_geojson, "w", encoding="utf-8"), ensure_ascii=False)

payload = {
    "DATASET": data["meta"]["dataset"],
    "FEATURES": data["features"],
    "SCALES": data["sig_scales"],
    "SIGNATURES": data["signatures"],
    "ACTIVE": data["active_classes"],
    "PRIORS": data["prevalence_priors"],
    "BOURJ": bourj,
}
body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
js = (
    "/* Generated by scripts/delta_vision/ref/make_data.py from the engine's spectral data file — do not edit by hand. */\n"
    '(function (root, factory) {\n'
    '  if (typeof module === "object" && module.exports) module.exports = factory();\n'
    '  else root.DVData = factory();\n'
    '})(typeof self !== "undefined" ? self : this, function () {\n'
    '  "use strict";\n'
    "  return " + body + ";\n"
    "});\n"
)
open(out_js, "w", encoding="utf-8").write(js)
print("written:", out_js, len(js), "bytes;", out_geojson)
